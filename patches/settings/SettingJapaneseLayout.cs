    public static void Apply(GameObject settingRoot)
    {
        if (settingRoot == null)
            return;

        UILabel[] labels = settingRoot.GetComponentsInChildren<UILabel>(true);
        for (int i = 0; i < labels.Length; ++i)
        {
            UILabel label = labels[i];
            if (label == null)
                continue;

            string original = label.text == null ? "" : label.text;
            string translated;
            if (Translations.TryGetValue(original, out translated))
                label.text = translated;
        }
    }
